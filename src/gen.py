"""Generate PatchData.cs for the Racer mod installer from ..\\stages (see make_stages.ps1).

Each stage is the exe after one more mod, replayed from the stock GOG exe in the order the mods
were applied. The bytes a stage changes belong to that mod. No two mods change the same byte
(checked here), so any combination can be applied to the stock exe laid out with all three added
sections (.movie, .split, .racer), which are left zero-filled for mods that are off.

Usage: gen.py <stages dir> <stock Sounds.map> <output PatchData.cs>
"""
import hashlib
import struct
import sys

stages_dir, sounds_path, out_path = sys.argv[1:4]
ORDER = [('ai', '1-ai'), ('movies', '2-movies'), ('split', '3-split'), ('boost', '4-boost'),
         ('pod', '5-pod'), ('laa', '6-laa'), ('hangar', '7-hangar'), ('extra', '8-extra')]
STOCK_MD5 = 'E1FCF50C8DE2DBEF70E6AD8E09371322'
HEADER = 0x400
FREEPLAY_RECORDS = 0xD633C          # split screen option byte (VA 0xEDE33C)

def rd(n):
    return open('%s\\%s.exe' % (stages_dir, n), 'rb').read()

stock = rd('0-stock')
assert hashlib.md5(stock).hexdigest().upper() == STOCK_MD5
final = rd('8-extra')
pe = struct.unpack_from('<I', final, 0x3C)[0]
LAA = pe + 22

owner = {}
runs = {}
prev = stock
for key, name in ORDER:
    cur = rd(name)
    changed = []
    for k in range(HEADER, len(cur)):
        old = prev[k] if k < len(prev) else 0
        if cur[k] != old:
            assert k not in owner, 'byte 0x%X changed by both %s and %s' % (k, owner[k], key)
            owner[k] = key
            changed.append(k)
    # the header is shared: only the LAA bit may differ between stages beyond section bookkeeping
    if key == 'laa':
        diff = [k for k in range(HEADER) if cur[k] != prev[k]]
        assert diff == [LAA] and cur[LAA] ^ prev[LAA] == 0x20, diff
    rs = []
    for k in changed:
        if rs and rs[-1][0] + len(rs[-1][1]) == k:
            rs[-1][1].append(cur[k])
        else:
            rs.append((k, bytearray([cur[k]])))
    runs[key] = rs
    prev = cur
    print('%-7s %4d runs %6d bytes' % (key, len(rs), len(changed)))

assert final[FREEPLAY_RECORDS] == 0 and owner.get(FREEPLAY_RECORDS) is None
# the split code must read the option byte (VA 0xEDE33C) from its own bytes
ref = struct.pack('<I', 0xEDE33C)
assert any(owner.get(k) == 'split' for k in range(len(final)) if final[k:k + 4] == ref)

header = bytearray(final[:HEADER])
header[LAA] &= ~0x20 & 0xFF

# Rebuilding every mod on must give the final stage exactly.
img = bytearray(stock) + bytearray(len(final) - len(stock))
img[:HEADER] = header
img[LAA] |= 0x20
for key, _ in ORDER:
    for off, data in runs[key]:
        img[off:off + len(data)] = data
assert bytes(img) == final, 'all-on rebuild differs from the final stage'
FINAL_MD5 = hashlib.md5(final).hexdigest().upper()

# Portraits: the two sprites the extra racers patch appends (Jinn, Cy).
sb = open('%s\\out_spriteblock.bin' % stages_dir, 'rb').read()
be = lambda o: struct.unpack_from('>I', sb, o)[0]
assert be(0) == 181
a, m, z = be(4 + 4 * 179), be(4 + 4 * 180), be(4 + 4 * 181)
jinn, cy = sb[a:m], sb[m:z]
assert len(jinn) == len(cy) == 4644 and z == len(sb)

# Stock Sounds.map lines for sound ids 0xB0-0xB3 (player 2's engine), restored when split is off.
lines = open(sounds_path, 'rb').read().decode('latin-1').replace('\r\n', '\n').split('\n')
ids = [i for i, l in enumerate(lines) if not (l.strip() == '' or l.lstrip().startswith('#') or l.lstrip().startswith('NUMSOUNDS'))]
stock_b0 = [lines[ids[0xB0 + k]] for k in range(4)]
assert 'chop_a_combo' in lines[ids[0xAA]] and 'varispeed_comb' in lines[ids[0xAD]]

def cs(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\t', '\\t') + '"'

def hexlines(b, w=200):
    h = bytes(b).hex().upper()
    return ' +\n        '.join('"%s"' % h[i:i + w] for i in range(0, len(h), w)) or '""'

o = []
o.append('// Generated by gen.py from the replayed patch stages. Do not edit.')
o.append('static class PatchData {')
o.append('    public const string StockMd5 = "%s";' % STOCK_MD5)
o.append('    public const string AllOnMd5 = "%s";' % FINAL_MD5)
o.append('    public const int StockLength = %d, ModdedLength = %d;' % (len(stock), len(final)))
o.append('    public const int LaaOffset = 0x%X, FreePlayRecordsOffset = 0x%X;' % (LAA, FREEPLAY_RECORDS))
o.append('    public static readonly string Header =\n        %s;' % hexlines(header))
o.append('    public static readonly string[] Keys = { %s };' % ', '.join(cs(k) for k, _ in ORDER if k != 'laa'))
o.append('    public static readonly object[][] Runs = {')
for key, _ in ORDER:
    if key == 'laa':
        continue
    o.append('        new object[] { %s,' % cs(key))
    for off, data in runs[key]:
        o.append('            0x%X, %s,' % (off, hexlines(data)))
    o.append('        },')
o.append('    };')
o.append('    public static readonly string JinnSprite =\n        %s;' % hexlines(jinn))
o.append('    public static readonly string CySprite =\n        %s;' % hexlines(cy))
o.append('    public static readonly string[] StockSoundsB0 = { %s };' % ', '.join(cs(s) for s in stock_b0))
o.append('}')
open(out_path, 'w', newline='\r\n', encoding='ascii').write('\n'.join(o) + '\n')
print('all-on MD5', FINAL_MD5)
